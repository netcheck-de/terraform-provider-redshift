// PlanModifyList fills unknown encoding and nullable values that configuration leaves out.
func (tableColumnDefaults) PlanModifyList(ctx context.Context, req planmodifier.ListRequest, resp *planmodifier.ListResponse) {
	if req.PlanValue.IsNull() || req.PlanValue.IsUnknown() || req.ConfigValue.IsUnknown() {
		return
	}
	var planned, configured, existing []tableColumnModel
	if req.PlanValue.ElementsAs(ctx, &planned, false).HasError() || req.ConfigValue.ElementsAs(ctx, &configured, false).HasError() || len(planned) != len(configured) {
		return
	}
	prior := map[string]tableColumnModel{}
	if !req.StateValue.IsNull() && !req.StateValue.IsUnknown() && !req.StateValue.ElementsAs(ctx, &existing, false).HasError() {
		for _, column := range existing {
			prior[column.Name.ValueString()] = column
		}
	}
	var primaryKey types.List
	keyed := !req.Config.GetAttribute(ctx, path.Root("primary_key"), &primaryKey).HasError() && !primaryKey.IsUnknown()
	keys := map[string]bool{}
	if keyed {
		for _, element := range primaryKey.Elements() {
			if name, ok := element.(types.String); ok {
				keys[name.ValueString()] = true
			}
		}
	}
	moved, allMoved := tableSortKeyMoves(ctx, req.Config, req.State)
	for i := range planned {
		name := planned[i].Name.ValueString()
		before, existed := prior[name]
		if configured[i].Encoding.IsNull() && existed && !before.Encoding.IsUnknown() && !allMoved && !moved[name] {
			planned[i].Encoding = before.Encoding
		}
		if !configured[i].Nullable.IsNull() {
			continue
		}
		switch {
		case !configured[i].Identity.IsNull() || keys[planned[i].Name.ValueString()]:
			planned[i].Nullable = types.BoolValue(false)
		case existed && !before.Nullable.IsUnknown() && !before.Nullable.IsNull():
			planned[i].Nullable = before.Nullable
		case keyed && !configured[i].Identity.IsUnknown():
			planned[i].Nullable = types.BoolValue(true)
		}
	}
	list, diagnostics := types.ListValueFrom(ctx, req.PlanValue.ElementType(ctx), planned)
	if diagnostics.HasError() {
		return
	}
	resp.PlanValue = list
}

// tableSortKeyMoves returns the columns of the prior and configured sort key when the sort key changes, because
// ALTER SORTKEY may re-encode them: "When you alter a sort key, the compression encoding of columns in the new or
// original sort key can change." all is true when the changed key's columns are not all known, as for an unknown
// configuration or a key Redshift chose under AUTO. https://docs.aws.amazon.com/redshift/latest/dg/r_ALTER_TABLE.html
func tableSortKeyMoves(ctx context.Context, config tfsdk.Config, state tfsdk.State) (map[string]bool, bool) {
	if state.Raw.IsNull() {
		return nil, false
	}
	var configStyle, stateStyle types.String
	var configKey, stateKey types.List
	if config.GetAttribute(ctx, path.Root("sortkey_style"), &configStyle).HasError() || config.GetAttribute(ctx, path.Root("sortkey"), &configKey).HasError() ||
		state.GetAttribute(ctx, path.Root("sortkey_style"), &stateStyle).HasError() || state.GetAttribute(ctx, path.Root("sortkey"), &stateKey).HasError() {
		return nil, false
	}
	if configStyle.IsUnknown() || configKey.IsUnknown() {
		return nil, true
	}
	style := func(configured types.String, key types.List) string {
		switch {
		case !configured.IsNull() && !configured.IsUnknown():
			return configured.ValueString()
		case len(key.Elements()) > 0:
			return "COMPOUND"
		}
		return "AUTO"
	}
	from, to := style(stateStyle, stateKey), style(configStyle, configKey)
	fromNames, fromErr := tableStringList(stateKey, "sortkey")
	toNames, toErr := tableStringList(configKey, "sortkey")
	switch {
	case fromErr != nil || toErr != nil:
		return nil, true
	case from == to && slices.Equal(fromNames, toNames):
		return nil, false
	}
	columns := map[string]bool{}
	for _, name := range append(fromNames, toNames...) {
		columns[name] = true
	}
	return columns, from == "AUTO"
}

// read refreshes the table under the configured binding. It reports false when the table, its schema, or its
// database is gone, and returns the constraint names an update needs to drop constraints.
func (r *tableResource) read(ctx context.Context, data *tableModel) (bool, map[string]string, error) {
	database := data.Database.ValueString()
	if err := r.bound(data.ID, database); err != nil {
		return false, nil, err
	}
	if exists, err := r.localDatabaseExists(ctx, database); err != nil || !exists {
		return false, nil, err
	}
	spec := tableSpec{schema: data.Schema.ValueString(), name: data.Name.ValueString()}
	tables, err := r.selectRows(ctx, database, readTableQuery(spec))
	if err != nil || len(tables) == 0 {
		return false, nil, err
	}
	if len(tables) != 1 {
		return false, nil, fmt.Errorf("table %q.%q has ambiguous catalog metadata", spec.schema, spec.name)
	}
	attributes, err := r.selectRows(ctx, database, readTableAttributesQuery(spec))
	if err != nil {
		return false, nil, err
	}
	columns, err := r.selectRows(ctx, database, readTableColumnsQuery(database, spec))
	if err != nil {
		return false, nil, err
	}
	constraints, err := r.selectRows(ctx, database, readTableConstraintsQuery(spec))
	if err != nil {
		return false, nil, err
	}
	catalog, err := tableCatalogFrom(tables[0], attributes, columns, constraints)
	if err != nil {
		return false, nil, fmt.Errorf("table %q.%q: %w", spec.schema, spec.name, err)
	}
	if knownString(data.SortKeyStyle) == "AUTO" && tableCatalogCompoundSortKey(catalog) {
		rows, err := r.selectRows(ctx, database, readTableSortKeyQuery(spec))
		if err != nil {
			return false, nil, err
		}
		// ALTER SORTKEY AUTO keeps the current key, and SVV_TABLE_INFO lists only tables with rows, so only an
		// explicit sortkey1 proves that the key is no longer automatic.
		catalog.autoSortKey = len(rows) == 0 || strings.HasPrefix(strings.ToUpper(strings.TrimSpace(rows[0]["sortkey1"])), "AUTO(")
	}
	observed, names, err := tableReconcile(*data, catalog)
	if err != nil {
		return false, nil, fmt.Errorf("table %q.%q: %w", spec.schema, spec.name, err)
	}
	*data = observed
	return true, names, nil
}

// tableCatalogCompoundSortKey reports sort key columns without interleaving, which SORTKEY AUTO can also produce.
func tableCatalogCompoundSortKey(catalog tableCatalog) bool {
	return slices.ContainsFunc(catalog.columns, func(c tableCatalogColumn) bool { return c.sortKey > 0 }) &&
		!slices.ContainsFunc(catalog.columns, func(c tableCatalogColumn) bool { return c.sortKey < 0 })
}

// tableKnownState replaces unknown computed values with nulls, so state written before verification is complete
// and serializable.
func tableKnownState(data tableModel) tableModel {
	for _, value := range []*types.String{&data.Owner, &data.DistStyle, &data.SortKeyStyle, &data.Backup} {
		if value.IsUnknown() {
			*value = types.StringNull()
		}
	}
	var columns []tableColumnModel
	if data.Columns.ElementsAs(context.Background(), &columns, false).HasError() {
		return data
	}
	for i := range columns {
		if columns[i].Encoding.IsUnknown() {
			columns[i].Encoding = types.StringNull()
		}
		if columns[i].Nullable.IsUnknown() {
			columns[i].Nullable = types.BoolNull()
		}
	}
	if list, diagnostics := types.ListValueFrom(context.Background(), types.ObjectType{AttrTypes: tableColumnAttributeTypes}, columns); !diagnostics.HasError() {
		data.Columns = list
	}
	return data
}

// verify re-reads the table after Create or Update and stores it once the catalog matches the plan.
func (r *tableResource) verify(ctx context.Context, plan tableModel, state *tfsdk.State, diagnostics *diag.Diagnostics, absent string) {
	observed := plan
	found, _, err := r.read(ctx, &observed)
	switch {
	case err != nil:
		diagnostics.AddError("Verify table", err.Error())
		return
	case !found:
		diagnostics.AddError("Verify table", absent)
		return
	}
	planSpec, err := tableSpecOf(plan)
	if err == nil {
		var observedSpec tableSpec
		if observedSpec, err = tableSpecOf(observed); err == nil {
			err = tableConverged(planSpec, observedSpec)
		}
	}
	if err != nil {
		diagnostics.AddError("Verify table", "The catalog does not match the configuration after the change: "+err.Error())
		return
	}
	diagnostics.Append(state.Set(ctx, &observed)...)
}

// Create validates the definition, creates the table, transfers ownership, and verifies the catalog.
func (r *tableResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var data tableModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	spec, err := tableSpecOf(data)
	var statements []string
	if err == nil {
		statements, err = createTableStatements(spec)
	}
	if err != nil {
		resp.Diagnostics.AddError("Invalid table", err.Error())
		return
	}
	database := data.Database.ValueString()
	if err := r.exec(ctx, database, statements[0]); err != nil {
		resp.Diagnostics.AddError("Create table", err.Error())
		return
	}
	data.ID = r.identity(database, map[string]string{"schema": spec.schema, "name": spec.name})
	// A failed ownership change or verification must still leave state for the created table.
	known := tableKnownState(data)
	resp.Diagnostics.Append(resp.State.Set(ctx, &known)...)
	if err := r.exec(ctx, database, statements[1:]...); err != nil {
		resp.Diagnostics.AddError("Set table owner", err.Error())
		return
	}
	r.verify(ctx, data, &resp.State, &resp.Diagnostics, "The table is absent after creation.")
}

// ValidateConfig reports definitions Create would reject, during planning once the configuration is known.
func (r *tableResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var data tableModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() || !req.Config.Raw.IsFullyKnown() {
		return
	}
	if _, err := tableSpecOf(data); err != nil {
		resp.Diagnostics.AddError("Invalid table", err.Error())
	}
}

// Read refreshes the definition or removes a table whose table, schema, or database is gone.
func (r *tableResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data tableModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	found, _, err := r.read(ctx, &data)
	switch {
	case err != nil:
		resp.Diagnostics.AddError("Read table", err.Error())
	case !found:
		resp.State.RemoveResource(ctx)
	default:
		resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
	}
}

// Update applies the in-place changes from the table's current catalog definition and verifies the result.
func (r *tableResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, current tableModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &current)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if _, err := tableSpecOf(plan); err != nil {
		resp.Diagnostics.AddError("Invalid table", err.Error())
		return
	}
	found, constraints, err := r.read(ctx, &current)
	switch {
	case err != nil:
		resp.Diagnostics.AddError("Read table", err.Error())
		return
	case !found:
		resp.Diagnostics.AddError("Update table", "The table disappeared during the update; refresh the plan.")
		return
	}
	before, after, err := tableAlterStates(current, constraints, plan)
	database := plan.Database.ValueString()
	if err == nil {
		err = r.exec(ctx, database, tableAlterPhaseStatements(before, after, tablePhaseDropConstraints, tablePhaseAddColumns, tablePhaseKeys)...)
	}
	// ALTER SORTKEY can re-encode columns of the old and new key, so encodings are compared against the catalog
	// after the key change; the other phases still start from the definition before the update.
	encodings := before
	if err == nil && tableSortKeyReencodes(before.spec, after.spec) {
		encodings, err = r.refreshEncodings(ctx, plan)
	}
	if err == nil {
		err = r.exec(ctx, database, tableAlterPhaseStatements(encodings, after, tablePhaseAlterColumns)...)
	}
	if err == nil {
		err = r.exec(ctx, database, tableAlterPhaseStatements(before, after, tablePhaseDropColumns, tablePhaseRestoreKeys, tablePhaseAddConstraints, tablePhaseOwner)...)
	}
	if err != nil {
		resp.Diagnostics.AddError("Update table", err.Error())
		return
	}
	r.verify(ctx, plan, &resp.State, &resp.Diagnostics, "The table disappeared during the update.")
}

// refreshEncodings re-reads the table in the middle of an update, so the alter-columns phase starts from the
// encodings Redshift assigned during the sort key change.
func (r *tableResource) refreshEncodings(ctx context.Context, plan tableModel) (tableAlterState, error) {
	refreshed := plan
	found, names, err := r.read(ctx, &refreshed)
	switch {
	case err != nil:
		return tableAlterState{}, err
	case !found:
		return tableAlterState{}, fmt.Errorf("the table disappeared during the update")
	}
	spec, err := tableSpecOf(refreshed)
	if err != nil {
		return tableAlterState{}, fmt.Errorf("table definition after the sort key change: %w", err)
	}
	return tableAlterState{model: refreshed, spec: spec, constraints: names}, nil
}

// Delete drops the table without CASCADE and verifies its removal.
func (r *tableResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var data tableModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	found, _, err := r.read(ctx, &data)
	if err == nil && found {
		err = r.exec(ctx, data.Database.ValueString(), dropTableStatement(tableSpec{schema: data.Schema.ValueString(), name: data.Name.ValueString()}))
		if err == nil {
			found, _, err = r.read(ctx, &data)
			if err == nil && found {
				resp.Diagnostics.AddError("Delete table", "The table remains after deletion.")
			}
		}
	}
	if err != nil {
		resp.Diagnostics.AddError("Delete table", err.Error())
	}
}

// ImportState restores the table's database, schema, and name from its JSON identity.
func (r *tableResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	importIdentity(ctx, req, resp, "database", "schema", "name")
}
