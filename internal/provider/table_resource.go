// tableKeywordStrings converts an allowlist for schema validators.
func tableKeywordStrings(keywords []sqlclient.Keyword) []string {
	values := make([]string, len(keywords))
	for i, keyword := range keywords {
		values[i] = string(keyword)
	}
	return values
}

// tableRequiresReplace decides whether attribute's change needs a new table. Undecodable values replace, so a
// change is never applied in place without the checks that make ALTER TABLE succeed.
func tableRequiresReplace(ctx context.Context, state tfsdk.State, plan tfsdk.Plan, attribute string) bool {
	var prior, planned tableModel
	if state.Get(ctx, &prior).HasError() || plan.Get(ctx, &planned).HasError() {
		return true
	}
	prevSpec, err := tableSpecOf(prior)
	if err != nil {
		return true
	}
	planSpec, err := tableSpecOf(planned)
	if err != nil {
		return true
	}
	return tableReplacements(prevSpec, planSpec)[attribute] != ""
}

// tableDerivedStyle fills an omitted diststyle or sortkey_style from its key attribute, as Redshift would, so the
// plan shows the style and a drifted style is reset.
type tableDerivedStyle struct {
	// source is distkey or sortkey.
	source string
}

// Description explains the derived default.
func (m tableDerivedStyle) Description(context.Context) string {
	return "Defaults to the style implied by " + m.source + "."
}

// MarkdownDescription explains the derived default.
func (m tableDerivedStyle) MarkdownDescription(ctx context.Context) string { return m.Description(ctx) }

// PlanModifyString derives the style when it is not configured. Configuration it cannot read, as in schema
// tests, leaves the plan alone.
func (m tableDerivedStyle) PlanModifyString(ctx context.Context, req planmodifier.StringRequest, resp *planmodifier.StringResponse) {
	if !req.ConfigValue.IsNull() {
		return
	}
	if m.source == "distkey" {
		var key types.String
		if req.Config.GetAttribute(ctx, path.Root(m.source), &key).HasError() {
			return
		}
		switch {
		case key.IsUnknown():
			resp.PlanValue = types.StringUnknown()
		case key.IsNull():
			resp.PlanValue = types.StringValue("AUTO")
		default:
			resp.PlanValue = types.StringValue("KEY")
		}
		return
	}
	var key types.List
	if req.Config.GetAttribute(ctx, path.Root(m.source), &key).HasError() {
		return
	}
	switch {
	case key.IsUnknown():
		resp.PlanValue = types.StringUnknown()
	case key.IsNull() || len(key.Elements()) == 0:
		resp.PlanValue = types.StringValue("AUTO")
	default:
		resp.PlanValue = types.StringValue("COMPOUND")
	}
}

